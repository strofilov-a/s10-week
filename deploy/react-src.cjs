function promoReact(dir, outDir, SCOPE, KF, what) {
  const SOUT = path.join(ROOT, 'react-src', outDir);
  // the Kazan blocks on top (landing-kazan/intro/): their stylesheet and pictures inlined into the markup's shadow template
  const page = require('./kazan-intro-inline.cjs').inlineIntro(read(dir + '/index.html'), path.join(ROOT, dir));
  const stageCss = (page.match(/<link rel="stylesheet" href="((?:\.\.\/landing-v2\/)?scenes\/stage\.css)">/) || [])[1];
  if (!stageCss) fail(`${dir}: scenes/stage.css not linked`);
  const body = (page.match(/<body>\n([\s\S]*?)\n<script src="https:\/\/cdn\.jsdelivr\.net/) || [])[1];
  if (!body) fail(`${dir}: body markup not found`);
  if (/<script/.test(body)) fail(`${dir}: a script inside the markup`);
  const cssSrc = read(path.posix.join(dir, stageCss)) + '\n' + (page.match(/<style>\n([\s\S]*?)<\/style>/) || [])[1];
  const mapSel = (sel) => {
    sel = sel.trim();
    if (!sel) return sel;
    if (/^(:root|html|body)$/.test(sel)) return SCOPE;
    let m;
    if ((m = sel.match(/^html((?:\.[\w-]+)+)(?:\s+body)?(\s+.*)?$/))) return SCOPE + m[1] + (m[2] || '');
    if (/^(html|body)\b/.test(sel)) fail('landing: unhandled selector ' + sel);
    if (/^::?[\w-]+/.test(sel) && !/^:root/.test(sel)) return SCOPE + ' ' + sel;
    return SCOPE + ' ' + sel;
  };
  // a small brace walker: selectors of style rules get the scope, @media/@supports are walked into, @keyframes kept
  let out = '', i = 0;
  const keyframes = [];
  function block(stopAtClose) {
    let buf = '';
    while (i < cssSrc.length) {
      const c = cssSrc[i];
      if (c === '/' && cssSrc[i + 1] === '*') { const e = cssSrc.indexOf('*/', i + 2); buf += cssSrc.slice(i, e + 2); i = e + 2; continue; }
      if (c === '}') { if (stopAtClose) { i++; return buf + '}'; } fail('landing css: stray }'); }
      // read a prelude up to { or ;
      let j = i; while (j < cssSrc.length && cssSrc[j] !== '{' && cssSrc[j] !== '}' && !(cssSrc[j] === '/' && cssSrc[j + 1] === '*')) j++;
      if (cssSrc[j] !== '{') { buf += cssSrc.slice(i, j); i = j; if (cssSrc[j] === '}' ) continue; if (j >= cssSrc.length) break; continue; }
      const pre = cssSrc.slice(i, j), lead = pre.match(/^\s*/)[0], sel = pre.trim();
      i = j + 1;
      if (/^@(media|supports)/.test(sel)) { buf += lead + sel + ' {' + block(true); continue; }
      if (/^@(-webkit-)?keyframes/.test(sel)) { keyframes.push(sel.split(/\s+/)[1]); let d = 1, k = i; while (d) { if (cssSrc[k] === '{') d++; if (cssSrc[k] === '}') d--; k++; } buf += lead + sel + ' {' + cssSrc.slice(i, k); i = k; continue; }
      if (/^@font-face/.test(sel)) fail('landing css: @font-face in the page');
      const e = cssSrc.indexOf('}', i);
      buf += lead + sel.split(',').map(mapSel).join(', ') + ' {' + cssSrc.slice(i, e + 1);
      i = e + 1;
    }
    return buf;
  }
  out = block(false);
  for (const k of keyframes) out = out.replace(new RegExp(`(?<![\\w-])${k}(?![\\w-])`, 'g'), KF + k);
  fs.mkdirSync(SOUT, { recursive: true });
  fs.writeFileSync(path.join(SOUT, 'start.css'), `/* ${what} styles, from ${dir}/index.html and ${path.posix.join(dir, stageCss)}. GENERATED by
   deploy/react-src.cjs: every selector is under ${SCOPE}; the page's :root/html/body rules apply to that root.
   The classes the scripts set on <html> in the standalone page (js, is-smooth) are set on the root here. */
${out.trim()}\n`);
  if (outDir === 'kazan-start') fs.writeFileSync(path.join(SOUT, 'fonts.css'), `/* Roboto (variable 100–900), Cyrillic and Latin, from @fontsource 5.3.0 (SIL OFL 1.1), as data: URLs: the font of the Kazan
   blocks on top, which live in a shadow root (a font must be declared in the document, not there). GENERATED by
   deploy/react-src.cjs. Jost and Golos Text come from ../solo-start/fonts.css. */
${require('./fonts.cjs').ROBOTO}\n`);
  if (outDir === 'solo-start') fs.writeFileSync(path.join(SOUT, 'fonts.css'), `/* Jost (600–700) and Golos Text (400–600), Cyrillic and Latin, variable woff2 from @fontsource 5.3.0 (SIL OFL 1.1), as
   data: URLs so css-loader needs no rule for font files. GENERATED by deploy/react-src.cjs. */
${FONTS}\n`);
  fs.writeFileSync(path.join(SOUT, 'markup.ts'), `/* The markup of the ${what}, from ${dir}/index.html. GENERATED by deploy/react-src.cjs.
   ${outDir === 'solo-start' ? 'SoloStart' : 'KazanStart'}.tsx renders it as is; start.ts fills the calendar and the plan weeks and runs the scenes on it. */
export const MARKUP: string = ${JSON.stringify(body)};
`);
  console.log(`react-src: ${outDir}/markup.ts (${(body.length / 1024).toFixed(0)} KB), start.css (${(out.length / 1024).toFixed(0)} KB, keyframes ${keyframes.join(', ')})${outDir === 'solo-start' ? ', fonts.css' : ', fonts.css (Roboto)'}`);
}
