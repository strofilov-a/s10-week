function annotate(text) {
  const sf = ts.createSourceFile('engine.ts', text, ts.ScriptTarget.ES5, true, ts.ScriptKind.TS);
  const edits = [];
  const isEmpty = (e) => !e || e.kind === ts.SyntaxKind.NullKeyword || (ts.isIdentifier(e) && e.text === 'undefined')
    || (ts.isArrayLiteralExpression(e) && !e.elements.length) || (ts.isObjectLiteralExpression(e))
    || (ts.isNewExpression(e) && ts.isIdentifier(e.expression) && /^(Map|Set)$/.test(e.expression.text) && !e.typeArguments);
  (function walk(n) {
    if (ts.isParameter(n) && !n.type) {
      if (ts.isArrowFunction(n.parent) && n.parent.parameters.length === 1 && !/\(\s*$/.test(sf.text.slice(Math.max(0, n.getStart(sf) - 8), n.getStart(sf)))) {
        edits.push([n.getStart(sf), '('], [n.getEnd(), ': any)']);
      } else edits.push([n.name.getEnd(), ': any']);
    }
    if (ts.isVariableDeclaration(n) && !n.type && ts.isVariableDeclarationList(n.parent) && !ts.isForOfStatement(n.parent.parent) && !ts.isForInStatement(n.parent.parent)
      && isEmpty(n.initializer)) edits.push([n.name.getEnd(), ': any']);
    if (ts.isCatchClause(n)) return walk(n.block);
    ts.forEachChild(n, walk);
  })(sf);
  edits.sort((a, b) => b[0] - a[0]);
  for (const [pos, ins] of edits) text = text.slice(0, pos) + ins + text.slice(pos);
  return { text, n: edits.length };
}
